// Langue actuelle
let currentLang = localStorage.getItem('dyg-lang') || 'fr';

/**
 * Traduit un élément
 */
function translate(key, lang = currentLang) {
    return translations[lang][key] || translations['fr'][key] || key;
}

/**
 * Change la langue de tout le site
 */
function changeLang(lang) {
    currentLang = lang;
    localStorage.setItem('dyg-lang', lang);
    
    // Mettre à jour l'attribut lang du HTML
    document.documentElement.lang = lang;
    
    // Traduire tous les éléments avec data-i18n
    document.querySelectorAll('[data-i18n]').forEach(el => {
        const key = el.getAttribute('data-i18n');
        const translation = translate(key, lang);
        
        // Si l'élément a data-i18n-html, utiliser innerHTML
        if (el.hasAttribute('data-i18n-html')) {
            el.innerHTML = translation;
        }
        // Si c'est un input ou textarea, modifier le placeholder
        else if (el.tagName === 'INPUT' || el.tagName === 'TEXTAREA') {
            el.placeholder = translation;
        }
        // Si c'est un label avec for, modifier le textContent
        else if (el.tagName === 'LABEL') {
            el.textContent = translation;
        }
        // Sinon, modifier le textContent
        else {
            el.textContent = translation;
        }
    });
    
    // Mettre à jour les boutons de langue
    document.querySelectorAll('.lang-btn').forEach(btn => {
        btn.classList.remove('active');
        if (btn.getAttribute('data-lang') === lang) {
            btn.classList.add('active');
        }
    });
    
    console.log('✅ Langue changée:', lang);
}

/**
 * Initialisation au chargement de la page
 */
document.addEventListener('DOMContentLoaded', () => {
    // Appliquer la langue sauvegardée
    changeLang(currentLang);
    
    // Écouter les clics sur les boutons de langue
    document.querySelectorAll('.lang-btn').forEach(btn => {
        btn.addEventListener('click', () => {
            const lang = btn.getAttribute('data-lang');
            changeLang(lang);
        });
    });
});

// Exposer les fonctions globalement
window.changeLang = changeLang;
window.translate = translate;
